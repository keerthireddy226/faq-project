// Regenerates src/components/course/countryNames.ts from the currently-installed
// intl-tel-input package, so the static iso2 -> name map stays in sync whenever
// intl-tel-input is upgraded (new/renamed countries).
//
// Names must be a deterministic snapshot (not computed at render time) because
// the country <select> is server-rendered: runtime Intl.DisplayNames differs
// between Node and the browser and breaks React hydration.
//
// Run: npm run gen:countries  (also runs automatically via prebuild)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const DATA_FILE = resolve(
  root,
  "node_modules/intl-tel-input/dist/js/data.mjs",
);
const OUT_FILE = resolve(root, "src/components/course/countryNames.ts");

// Names for iso2 codes that Intl.DisplayNames doesn't resolve to a real name.
const NAME_OVERRIDES = {
  ac: "Ascension Island",
  ta: "Tristan da Cunha",
  xk: "Kosovo",
};

const src = readFileSync(DATA_FILE, "utf8");
// Each country tuple starts with its iso2 as the first string: ["af", "93", ...]
const codes = [...src.matchAll(/\[\s*"([a-z]{2})"\s*,/g)].map((m) => m[1]);
const uniq = [...new Set(codes)];

const dn = new Intl.DisplayNames(["en"], { type: "region" });
const nameOf = (iso2) => {
  const code = iso2.toUpperCase();
  const name = NAME_OVERRIDES[iso2] ?? dn.of(code);
  return name && name !== code ? name : code;
};

const entries = uniq
  .map((iso2) => [iso2, nameOf(iso2)])
  .sort((a, b) => a[0].localeCompare(b[0]));

const body = entries
  .map(([iso2, name]) => `  ${iso2}: ${JSON.stringify(name)},`)
  .join("\n");

const content = `// AUTO-GENERATED by scripts/generate-country-names.mjs — do not edit by hand.
// Static iso2 -> English country name map, snapshotted from intl-tel-input so the
// <select> renders identical text on the server and client (no hydration errors).
// Regenerate with: npm run gen:countries
const countryNames: Record<string, string> = {
${body}
};

export default countryNames;
`;

writeFileSync(OUT_FILE, content);
console.log(`Wrote ${OUT_FILE} (${entries.length} countries)`);
